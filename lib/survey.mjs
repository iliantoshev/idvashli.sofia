// Проверява отговорите. Връща изчистен обект или null, ако нещо липсва.
export function cleanAnswers(input) {
  if (!input || typeof input !== 'object') return null;
  const out = {};
  for (const q of SURVEY) {
    const v = input[q.id];
    const valid = (i) => Number.isInteger(i) && i >= 0 && i < q.options.length;
    if (q.type === 'one') {
      if (!valid(v)) return null;
      out[q.id] = v;
    } else {
      if (!Array.isArray(v) || !v.length || !v.every(valid)) return null;
      const uniq = [...new Set(v)].sort((a, b) => a - b);
      if (q.exclusive !== undefined && uniq.includes(q.exclusive) && uniq.length > 1) return null;
      out[q.id] = uniq;
    }
  }
  return out;
}
